import type { Metadata } from 'next';
import Link from 'next/link';
import { Suspense } from 'react';
import { notFound } from 'next/navigation';
import { getCoronerReport, getSite, getSites } from '@/lib/data';
import { spineNumber } from '@/components/closet/TextureFactory';
import { ForensicsPanel } from '@/components/hud/ForensicsPanel';
import { CoronerPanel } from '@/components/hud/CoronerPanel';
import { SeanceChat } from '@/components/hud/SeanceChat';
import { OfrendaPanel } from '@/components/hud/OfrendaPanel';

export function generateStaticParams() {
  return getSites().map((s) => ({ id: s.id }));
}

export async function generateMetadata({ params }: PageProps<'/site/[id]'>): Promise<Metadata> {
  const { id } = await params;
  const site = getSite(id);
  if (!site) return {};
  return {
    title: `${site.title} (${site.firstCaptured}–${site.lastCaptured}) — Closet 404`,
    description: site.eulogy,
  };
}

function Heading({ children }: { children: React.ReactNode }) {
  return <h2 className="font-mono text-[11px] tracking-[0.22em] text-marigold mb-4">{children}</h2>;
}

export default function SiteDossierPage({ params }: PageProps<'/site/[id]'>) {
  return (
    <Suspense
      fallback={<main className="min-h-dvh bg-bg flex items-center justify-center font-mono text-[11px] text-muted">lighting the candles…</main>}
    >
      <SiteDossier params={params} />
    </Suspense>
  );
}

async function SiteDossier({ params }: { params: PageProps<'/site/[id]'>['params'] }) {
  const { id } = await params;
  const site = getSite(id);
  if (!site) notFound();
  const coroner = getCoronerReport(id);

  return (
    <main className="min-h-dvh bg-bg text-ink">
      <div className="mx-auto max-w-[1180px] px-4 sm:px-8 py-10 sm:py-14">
        <nav className="flex justify-between font-mono text-[11px] tracking-[0.2em] text-muted">
          <Link href="/" className="hover:text-marigold">← THE CLOSET</Link>
          <Link href="/archive" className="hover:text-marigold">THE INDEX →</Link>
        </nav>

        <header className="mt-10 grid lg:grid-cols-[1fr_380px] gap-10 border-b border-hairline pb-10">
          <div>
            <p className="font-mono text-[12px] text-muted">
              <span className="text-marigold">{spineNumber(site.spine)}</span> · {site.category.toUpperCase()} · first
              captured {site.firstCaptured} · last captured {site.lastCaptured}
            </p>
            <h1 className="font-display text-[clamp(48px,7vw,88px)] leading-[0.95] mt-3">{site.title}</h1>
            <a href={site.viewUrl} target="_blank" rel="noreferrer" className="font-mono text-[13px] text-muted hover:text-marigold break-all">
              {site.url} · view the {site.snapshotTimestamp.slice(0, 4)} snapshot on archive.org ↗
            </a>
          </div>
          <figure className="self-end">
            <blockquote className="font-display italic text-[24px] leading-snug text-ink/90">&ldquo;{site.eulogy}&rdquo;</blockquote>
            <figcaption className="mt-2 font-mono text-[10px] tracking-[0.12em] text-muted">
              EULOGY · AI-GENERATED BY {site.generatedBy.toUpperCase()}
            </figcaption>
          </figure>
        </header>

        <div className="grid lg:grid-cols-2 gap-12 mt-12">
          <section className="flex flex-col">
            <Heading>SÉANCE</Heading>
            <SeanceChat site={site} compact />
          </section>
          <section>
            <Heading>CORONER</Heading>
            <CoronerPanel site={site} report={coroner} />
          </section>
          <section>
            <Heading>REMAINS</Heading>
            <ForensicsPanel site={site} />
          </section>
          <section>
            <Heading>OFRENDA</Heading>
            <OfrendaPanel site={site} />
            <div className="mt-10">
              <Heading>GHOST PERSONA · AI-GENERATED</Heading>
              <p className="text-[14px] text-ink/75 leading-relaxed">{site.ghostPersona}</p>
              <p className="mt-3 flex flex-wrap gap-1.5">
                {site.vibeTags.map((t) => (
                  <span key={t} className="font-mono text-[10px] px-2 py-0.5 rounded-full border border-hairline text-muted">
                    {t}
                  </span>
                ))}
              </p>
            </div>
          </section>
        </div>
      </div>
    </main>
  );
}
