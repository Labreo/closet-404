'use client';

import React, { useState } from 'react';
import Link from 'next/link';
import type { CoronerReport, Site } from '@/types/archive';
import { SeanceChat } from './SeanceChat';
import { CoronerPanel } from './CoronerPanel';
import { ForensicsPanel } from './ForensicsPanel';
import { OfrendaPanel } from './OfrendaPanel';
import { spineNumber } from '@/components/closet/TextureFactory';

type Tab = 'seance' | 'coroner' | 'remains' | 'ofrenda';

const TABS: { id: Tab; label: string }[] = [
  { id: 'seance', label: 'Séance' },
  { id: 'coroner', label: 'Coroner' },
  { id: 'remains', label: 'Remains' },
  { id: 'ofrenda', label: 'Ofrenda' },
];

interface SiteDrawerProps {
  site: Site;
  coroner?: CoronerReport;
  ephemeral?: boolean;
  onClose: () => void;
}

export function SiteDrawer({ site, coroner, ephemeral = false, onClose }: SiteDrawerProps) {
  // The parent keys this component by site id, so the tab resets per case.
  const [tab, setTab] = useState<Tab>('seance');

  return (
    <aside
      className="drawer-in panel absolute right-3 top-3 bottom-3 z-30 w-[460px] max-w-[calc(100vw-24px)] rounded-2xl flex flex-col overflow-hidden"
    >
      <header className="px-6 pt-5 pb-4 border-b border-hairline">
        <div className="flex items-center justify-between gap-3">
          <div className="flex items-center gap-2 font-mono text-[11px]">
            <span className="text-marigold">{spineNumber(site.spine)}</span>
            <span className="text-muted uppercase tracking-[0.14em]">{site.category}</span>
            <span className="text-muted">
              {site.firstCaptured}–{site.lastCaptured}
            </span>
            {ephemeral && <span className="text-marigold/80">· resurrected live</span>}
          </div>
          <button
            type="button"
            onClick={onClose}
            className="flex items-center gap-1.5 text-muted hover:text-ink font-mono text-[11px]"
            aria-label="Put the case back"
          >
            <span className="kbd">Esc</span> put back
          </button>
        </div>
        <h2 className="font-display text-[34px] leading-[1.05] mt-2 text-ink">{site.title}</h2>
        <a
          href={site.viewUrl}
          target="_blank"
          rel="noreferrer"
          className="font-mono text-[11px] text-muted hover:text-marigold break-all"
        >
          {site.url} · snapshot {site.snapshotTimestamp.slice(0, 4)} ↗
        </a>
        <figure className="mt-4">
          <blockquote className="font-display italic text-[19px] leading-snug text-ink/90">
            &ldquo;{site.eulogy}&rdquo;
          </blockquote>
          <figcaption className="mt-1.5 font-mono text-[10px] tracking-[0.12em] text-muted">
            EULOGY · AI-GENERATED BY {site.generatedBy.toUpperCase()} FROM THE SNAPSHOT
          </figcaption>
        </figure>
      </header>

      <nav className="flex px-4 gap-1 border-b border-hairline">
        {TABS.map((t) => (
          <button
            key={t.id}
            type="button"
            onClick={() => setTab(t.id)}
            className={`px-3 py-2.5 font-label text-[13px] border-b-2 -mb-px transition-colors ${
              tab === t.id ? 'border-marigold text-ink' : 'border-transparent text-muted hover:text-ink'
            }`}
          >
            {t.label}
          </button>
        ))}
      </nav>

      <div className="flex-1 min-h-0 overflow-y-auto thin-scroll px-6 py-5 flex flex-col">
        {tab === 'seance' && <SeanceChat site={site} ephemeral={ephemeral} />}
        {tab === 'coroner' && <CoronerPanel site={site} report={coroner} />}
        {tab === 'remains' && <ForensicsPanel site={site} />}
        {tab === 'ofrenda' && <OfrendaPanel site={site} />}
      </div>

      {!ephemeral && (
        <footer className="px-6 py-3 border-t border-hairline flex justify-between font-mono text-[11px] text-muted">
          <Link href={`/site/${site.id}`} className="hover:text-marigold">
            Open full dossier →
          </Link>
          <a href={site.rawUrl} target="_blank" rel="noreferrer" className="hover:text-marigold">
            Raw HTML (id_) ↗
          </a>
        </footer>
      )}
    </aside>
  );
}
