'use client';

import React, { useState } from 'react';
import type { CoronerReport, Site } from '@/types/archive';

/** Turns [n] markers into links to the numbered sources. */
function withCitations(text: string, report: CoronerReport): React.ReactNode[] {
  return text.split(/(\[\d+\])/g).map((part, i) => {
    const m = /^\[(\d+)\]$/.exec(part);
    const source = m ? report.sources[Number(m[1]) - 1] : undefined;
    return source ? (
      <a key={i} href={source.link} target="_blank" rel="noreferrer" className="text-marigold font-mono text-[12px] align-super">
        {part}
      </a>
    ) : (
      <React.Fragment key={i}>{part}</React.Fragment>
    );
  });
}

export function CoronerPanel({ site, report: initial }: { site: Site; report?: CoronerReport }) {
  const [report, setReport] = useState<CoronerReport | undefined>(initial);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function inquest() {
    setBusy(true);
    setError(null);
    try {
      const res = await fetch('/api/coroner', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ site }),
      });
      if (!res.ok) {
        setError(await res.text());
        return;
      }
      setReport((await res.json()) as CoronerReport);
    } catch {
      setError('The coroner could not be reached.');
    } finally {
      setBusy(false);
    }
  }

  if (!report) {
    return (
      <div className="space-y-4">
        <p className="text-[13px] text-ink/80 leading-relaxed">
          The snapshot only remembers {site.title} alive. To learn how it ended, the coroner searches what the living
          wrote afterwards (a live Google search via SerpApi), and Gemma summarises only what those sources say.
        </p>
        <button
          type="button"
          onClick={() => void inquest()}
          disabled={busy}
          className="px-4 py-2 rounded-full border border-marigold text-marigold font-mono text-[12px] hover:bg-marigold hover:text-[#0c0b0e] disabled:opacity-50"
        >
          {busy ? 'Searching the records of the living…' : 'Hold an inquest'}
        </button>
        {error && <p className="font-mono text-[11px] text-[#d98b6b]">{error}</p>}
      </div>
    );
  }

  return (
    <div className="space-y-5">
      <section>
        <h3 className="font-mono text-[10px] tracking-[0.18em] text-marigold">CORONER&apos;S FINDING</h3>
        <p className="mt-2 font-display text-[21px] leading-snug text-ink">{withCitations(report.summary, report)}</p>
        <p className="mt-2 font-mono text-[10px] tracking-[0.12em] text-muted">
          AI-GENERATED BY {report.generatedBy.toUpperCase()} · ONLY FROM THE SOURCES BELOW
        </p>
      </section>
      <section className="space-y-3">
        <h3 className="font-mono text-[10px] tracking-[0.18em] text-marigold">
          EVIDENCE <span className="text-muted">· web search via SerpApi, {report.searchedAt.slice(0, 10)}</span>
        </h3>
        <ol className="space-y-3">
          {report.sources.map((s, i) => (
            <li key={s.link} className="grid grid-cols-[22px_1fr] gap-1">
              <span className="font-mono text-[11px] text-marigold">[{i + 1}]</span>
              <div>
                <a href={s.link} target="_blank" rel="noreferrer" className="text-[13px] text-ink hover:text-marigold leading-snug">
                  {s.title}
                </a>
                <p className="font-mono text-[10px] text-muted mt-0.5">
                  {s.source}
                  {s.date ? ` · ${s.date}` : ''}
                </p>
                <p className="text-[12px] text-ink/65 mt-1 leading-snug">{s.snippet}</p>
              </div>
            </li>
          ))}
        </ol>
        <p className="font-mono text-[10px] text-muted break-words">query: {report.query}</p>
      </section>
    </div>
  );
}
